-- PINPOINT leaderboard setup — run once in the Supabase SQL Editor.

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  player_id uuid not null default gen_random_uuid(),
  name text not null default 'GUEST',
  score int not null check (score >= 0 and score <= 99999),
  day_key int not null check (day_key >= 20200101),
  duration_ms int not null check (duration_ms >= 1000 and duration_ms <= 3600000),
  taps text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists scores_day_score_idx on public.scores (day_key, score desc);
create index if not exists scores_score_idx on public.scores (score desc);

alter table public.scores enable row level security;

drop policy if exists "public read scores" on public.scores;
create policy "public read scores" on public.scores for select using (true);

drop policy if exists "public insert scores" on public.scores;
create policy "public insert scores" on public.scores for insert with check (true);

-- Explicit Data API privileges (new Supabase projects may not auto-grant these).
-- The game has anonymous players and only needs read + insert access.
grant usage on schema public to anon;
grant select, insert on public.scores to anon;
